#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

# Verify schema, migrated objects, and grants without logging credentials.
docker compose exec -T oracle bash -s <<'CONTAINER'
set -euo pipefail
sqlplus -s / as sysdba <<'SQL'
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET LINESIZE 200 PAGESIZE 100
ALTER SESSION SET CONTAINER = FREEPDB1;
PROMPT === Created schema users ===
SELECT USERNAME FROM DBA_USERS
WHERE USERNAME IN ('WALLET_OWNER', 'WALLET_APP', 'WALLET_AUDIT') ORDER BY USERNAME;
PROMPT === Created objects ===
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE FROM DBA_OBJECTS
WHERE OWNER IN ('WALLET_OWNER','WALLET_AUDIT')
  AND OBJECT_TYPE IN ('SEQUENCE', 'TABLE')
ORDER BY OWNER, OBJECT_TYPE, OBJECT_NAME;
PROMPT === Audit grants to owner ===
SELECT GRANTEE, OWNER, TABLE_NAME, PRIVILEGE FROM DBA_TAB_PRIVS
WHERE OWNER = 'WALLET_AUDIT' AND GRANTEE = 'WALLET_OWNER'
ORDER BY TABLE_NAME, PRIVILEGE;
PROMPT === APP system privileges ===
SELECT GRANTEE, PRIVILEGE FROM DBA_SYS_PRIVS
WHERE GRANTEE = 'WALLET_APP' ORDER BY PRIVILEGE;
PROMPT === Unexpected APP table DML grants (expected NO ROWS) ===
SELECT OWNER, TABLE_NAME, PRIVILEGE FROM DBA_TAB_PRIVS
WHERE GRANTEE = 'WALLET_APP'
  AND PRIVILEGE IN ('INSERT', 'UPDATE', 'DELETE', 'ALTER')
ORDER BY OWNER, TABLE_NAME;
EXIT SUCCESS
SQL
CONTAINER
